/**
 * AI 分析结果数据结构
 *
 * 本文件定义 AI 经过解析后返回给用户的最终结果类型。
 * 这是用户最终看到的完整画像结构。
 *
 * 数据来源：
 * - AI 接收 AnalyzerOutput（见 analyzer-output/output-types.ts）作为输入
 * - 基于系统提示词（见 docs/prompt.md）进行多维分析
 * - 校验器 (parser/validator.ts) 对 AI 返回的 JSON 进行宽松校验
 *
 * 校验策略：
 * - 缺失字段用默认值填充，不直接报错
 * - 心理分数钳位到 0-100 范围
 * - 校验器返回 { data: AIAnalysisResult, warnings: string[] }
 */

// ============================================================================
// AI 分析最终结果
// ============================================================================

/**
 * AI 分析结果 — 用户最终看到的完整画像
 */
export interface AIAnalysisResult {
  /**
   * 用户画像总结
   * 一段自然语言描述，概括用户的整体特征
   * 默认值："数据缺失，无法生成摘要"
   */
  summary: string;

  // -------------------------
  // 专业画像
  // 基于帖子节点分布、内容深度和时间跨度推断
  // -------------------------

  professional: {
    /** 推断的技术栈列表，如 ["TypeScript", "React", "Node.js"] */
    tech_stack: string[];
    /** 职业方向推断，如 "全栈开发" / "前端工程师" */
    career_path: string;
    /** 技术水平推断，如 "初级" / "中级" / "高级" / "资深" */
    level: string;
    /** 技术关注一致性，如 "高度一致" / "多领域探索" */
    focus_coherence: string;
    /** 技术演变轨迹 */
    evolution: {
      /** 总体趋势描述 */
      summary: string;
      /** 按时间排列的关注点演变 */
      timeline: Array<{
        /** 时间段，如 "2019-2020" */
        period: string;
        /** 该时段的主要技术关注点 */
        focus: string;
      }>;
    };
  };

  // -------------------------
  // 个人生活画像
  // 基于非技术类帖子和回复内容推断
  // -------------------------

  personal: {
    /** 兴趣爱好，如 ["摄影", "骑行", "阅读"] */
    hobbies: string[];
    /** 人生阶段推断，如 "职场新人" / "已婚有子" / "自由职业" */
    life_stage: string;
    /** 价值观关键词，如 ["效率优先", "开源精神"] */
    values: string[];
  };

  // -------------------------
  // 心理画像 (OCEAN 大五人格模型)
  // 所有分数范围 0-100，超出范围会被钳位
  // -------------------------

  psychological: {
    scores: {
      /** 开放性 — 高=兴趣广泛爱尝新，低=务实保守 */
      openness: number;
      /** 尽责性 — 高=认真有条理，低=随性灵活 */
      conscientiousness: number;
      /** 外向性 — 高=社交活跃，低=内向独立 */
      extraversion: number;
      /** 宜人性 — 高=友善温和，低=直率犀利 */
      agreeableness: number;
      /** 神经质 — 高=情绪波动大，低=情绪稳定 */
      neuroticism: number;
    };
    /** 性格关键词标签，如 ["理性", "好奇", "直率"] */
    keywords: string[];
  };

  // -------------------------
  // 行为画像
  // 基于发帖/回复模式推断
  // -------------------------

  behavioral: {
    /** 社区角色，如 "内容创作者" / "讨论参与者" / "观察者" */
    role: string;
    /** 互动风格，如 "专业严谨" / "轻松幽默" / "直言不讳" */
    interaction_style: string;
    /** 活跃模式，如 "工作日活跃" / "夜间活跃" / "周末爆发" */
    active_pattern: string;
    /** 热点敏感度，如 "高"(追热点) / "中" / "低"(关注冷门) */
    heat_sensitivity: string;
  };

  // -------------------------
  // 社交画像
  // 基于内容吸引力和讨论参与深度推断
  // -------------------------

  social: {
    /** 内容吸引力特征，如 "技术干货" / "经验分享" / "问题驱动" */
    content_appeal: string;
    /** 讨论参与深度，如 "深度探讨" / "简短互动" / "一次性回复" */
    discussion_depth: string;
  };

  // -------------------------
  // 风险评估
  // 基于活动周期中断模式和前后内容风格差异推断
  // -------------------------

  risk: {
    /**
     * 风险等级
     * - 'safe': 正常用户，活动模式自然
     * - 'suspicious': 存在可疑特征，需进一步关注
     * - 'high_risk': 高度疑似账号异常（如买卖、被盗）
     */
    level: 'safe' | 'suspicious' | 'high_risk';
    /** 风险判断理由 */
    reason: string;
  };
}
