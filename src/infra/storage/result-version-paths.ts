import path from 'node:path';
import { isResultVersionId } from '@/core/result-version';
import { getUserDataDir } from './paths';

const RESULTS_DIRECTORY = 'results';
const VERSIONS_DIRECTORY = 'versions';
const INDEX_FILE = 'index.json';
const LOCK_FILE = '.write.lock';

/** Resolves the private directory that owns one user's saved result versions. */
export function getResultVersionsRootDir(username: string): string {
  return path.join(getUserDataDir(username), RESULTS_DIRECTORY);
}

/** Resolves the directory containing immutable result version files. */
export function getResultVersionFilesDir(username: string): string {
  return path.join(getResultVersionsRootDir(username), VERSIONS_DIRECTORY);
}

/** Resolves the validated result version index path. */
export function getResultVersionIndexPath(username: string): string {
  return path.join(getResultVersionsRootDir(username), INDEX_FILE);
}

/**
 * Resolves one immutable result version file.
 *
 * @param username - V2EX username that owns the saved result.
 * @param versionId - Canonical version ID generated by the application.
 * @returns An absolute path contained by the user's versions directory.
 * @throws {TypeError} When the version ID is not canonical.
 */
export function getResultVersionFilePath(username: string, versionId: string): string {
  if (!isResultVersionId(versionId)) {
    throw new TypeError(`Invalid result version ID: ${versionId}`);
  }

  return path.join(getResultVersionFilesDir(username), `${versionId}.json`);
}

/** Resolves the per-user lock that serializes result version writes. */
export function getResultVersionLockPath(username: string): string {
  return path.join(getResultVersionsRootDir(username), LOCK_FILE);
}
